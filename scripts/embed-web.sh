#!/bin/bash
# Regenerates Sources/remotemymac/WebAssets.swift from web/. Run after editing anything in web/.
set -euo pipefail
cd "$(dirname "$0")/.."
out=Sources/remotemymac/WebAssets.swift
{
  echo '// GENERATED by scripts/embed-web.sh from web/ - do not edit by hand.'
  echo 'enum WebAssets {'
  for pair in "html:index.html" "js:app.js" "css:app.css"; do
    echo "    static let ${pair%%:*} = #\"\"\""
    cat "web/${pair##*:}"
    echo '"""#'
  done
  echo '}'
} > "$out"
